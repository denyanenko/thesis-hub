interface LastNameEntry {
  male: string;
  female: string;
  key: string;
}

const ALL_LAST_NAMES: readonly LastNameEntry[] = (() => {
  const seen = new Set<string>();
  const entries: LastNameEntry[] = [];

  for (const name of UNISEX_LAST_NAMES) {
    if (!seen.has(name)) {
      seen.add(name);
      entries.push({ male: name, female: name, key: name });
    }
  }

  for (const [male, female] of GENDERED_LAST_NAMES) {
    if (!seen.has(male)) {
      seen.add(male);
      entries.push({ male, female, key: male });
    }
  }

  return entries;
})();

export function pickRandom<T>(items: readonly T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}

/**
 * Генерує коректне українське ПІБ з узгодженням статі (імʼя, по батькові, форма прізвища).
 * Якщо передано `usedLastNameKeys`, намагається підібрати прізвище, якого ще немає у цьому наборі.
 */
export function generateUkrainianPerson(
  usedLastNameKeys?: Set<string>,
  usedFullNames?: Set<string>,
): GeneratedPerson {
  for (let attempt = 0; attempt < 50; attempt += 1) {
    const gender: Gender = Math.random() < 0.52 ? 'male' : 'female';
    const firstName =
      gender === 'male'
        ? pickRandom(MALE_FIRST_NAMES)
        : pickRandom(FEMALE_FIRST_NAMES);
    const patronymic =
      gender === 'male'
        ? pickRandom(MALE_PATRONYMICS)
        : pickRandom(FEMALE_PATRONYMICS);

    let lastNameEntry = pickRandom(ALL_LAST_NAMES);
    if (usedLastNameKeys && usedLastNameKeys.size < ALL_LAST_NAMES.length) {
      for (let lnAttempt = 0; lnAttempt < 25; lnAttempt += 1) {
        if (!usedLastNameKeys.has(lastNameEntry.key)) break;
        lastNameEntry = pickRandom(ALL_LAST_NAMES);
      }
      if (usedLastNameKeys.has(lastNameEntry.key)) {
        const available = ALL_LAST_NAMES.filter(
          (entry) => !usedLastNameKeys.has(entry.key),
        );
        if (available.length > 0) {
          lastNameEntry = pickRandom(available);
        }
      }
    }

    const lastName =
      gender === 'male' ? lastNameEntry.male : lastNameEntry.female;
    const fullName = `${lastName} ${firstName} ${patronymic}`;

    if (!usedFullNames || !usedFullNames.has(fullName)) {
      usedLastNameKeys?.add(lastNameEntry.key);
      usedFullNames?.add(fullName);
      return {
        gender,
        firstName,
        lastName,
        patronymic,
        lastNameKey: lastNameEntry.key,
      };
    }
  }

  // Fallback на випадок вкрай великого обсягу даних
  const gender: Gender = Math.random() < 0.5 ? 'male' : 'female';
  const entry = pickRandom(ALL_LAST_NAMES);
  return {
    gender,
    firstName:
      gender === 'male'
        ? pickRandom(MALE_FIRST_NAMES)
        : pickRandom(FEMALE_FIRST_NAMES),
    lastName: gender === 'male' ? entry.male : entry.female,
    patronymic:
      gender === 'male'
        ? pickRandom(MALE_PATRONYMICS)
        : pickRandom(FEMALE_PATRONYMICS),
    lastNameKey: entry.key,
  };
}

